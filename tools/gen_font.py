from PIL import Image, ImageDraw, ImageFont
import sys
SIZES = [13, 18, 30, 54]
TTF = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
out_c = ["/* generated by gen_font.py - DejaVu Sans (Bitstream Vera license, free to embed) */",
         '#include "font_data.h"']
tables = []
for si, size in enumerate(SIZES):
    font = ImageFont.truetype(TTF, size)
    asc, desc = font.getmetrics()
    glyphs = []
    for code in range(32, 127):
        ch = chr(code)
        bbox = font.getbbox(ch, anchor="ls")  # relative to baseline origin
        w, h = max(0, bbox[2] - bbox[0]), max(0, bbox[3] - bbox[1])
        adv = font.getlength(ch)
        img = Image.new("L", (max(w, 1), max(h, 1)), 0)
        if w and h and ch != " ":
            ImageDraw.Draw(img).text((-bbox[0], -bbox[1]), ch, font=font, fill=255, anchor="ls")
        glyphs.append((img, w, h, bbox[0], bbox[1] + asc, adv))
    AW = 256 if size < 30 else 512
    x = y = rowh = 0
    place = []
    for img, w, h, xo, yo, adv in glyphs:
        if x + w + 1 > AW:
            x, y, rowh = 0, y + rowh + 1, 0
        place.append((x, y))
        x += w + 1
        rowh = max(rowh, h)
    AH = y + rowh + 1
    atlas = Image.new("L", (AW, AH), 0)
    for (img, w, h, xo, yo, adv), (px, py) in zip(glyphs, place):
        if w and h:
            atlas.paste(img, (px, py))
    data = list(atlas.getdata())
    out_c.append(f"static const unsigned char px{si}[{AW*AH}] = {{")
    line = []
    for i, v in enumerate(data):
        line.append(str(v))
        if len(line) == 32:
            out_c.append(",".join(line) + ","); line = []
    if line: out_c.append(",".join(line) + ",")
    out_c.append("};")
    g = ",".join("{%d,%d,%d,%d,%d,%d,%.3ff}" % (p[0], p[1], w, h, xo, yo, adv)
                 for (img, w, h, xo, yo, adv), p in zip(glyphs, place))
    tables.append(f"{{{AW},{AH},{asc+desc},{{{g}}},px{si}}}")
    print("size", size, "atlas", AW, AH, "lineh", asc + desc, file=sys.stderr)
out_c.append("const FontData font_data[%d] = {%s};" % (len(SIZES), ",\n".join(tables)))
open("src/font_data.c", "w").write("\n".join(out_c) + "\n")
open("src/font_data.h", "w").write("""#ifndef FONT_DATA_H
#define FONT_DATA_H
typedef struct { short x, y, w, h, xoff, yoff; float adv; } Glyph;
typedef struct { int aw, ah, lineh; Glyph g[95]; const unsigned char *px; } FontData;
extern const FontData font_data[4];
#endif
""")
